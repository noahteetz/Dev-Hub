CREATE TABLE IF NOT EXISTS projects (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(255) NOT NULL,
	description TEXT NOT NULL DEFAULT '',
	is_system BOOLEAN NOT NULL DEFAULT FALSE,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE projects ADD COLUMN IF NOT EXISTS is_system BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE projects ADD COLUMN IF NOT EXISTS repository_url VARCHAR(2048) NOT NULL DEFAULT '';
ALTER TABLE projects ADD COLUMN IF NOT EXISTS deployment_url VARCHAR(2048) NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS project_links (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	project_id BIGINT NOT NULL,
	label VARCHAR(255) NOT NULL,
	url VARCHAR(2048) NOT NULL,
	link_order INTEGER NOT NULL,
	CONSTRAINT project_links_project_fk
		FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE,
	CONSTRAINT project_links_project_order_unique UNIQUE (project_id, link_order)
);

CREATE TABLE IF NOT EXISTS notes (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	project_id BIGINT NOT NULL,
	title VARCHAR(255) NOT NULL,
	content TEXT NOT NULL,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT notes_project_fk
		FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS code_snippets (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	project_id BIGINT NOT NULL,
	title VARCHAR(255) NOT NULL,
	language VARCHAR(100) NOT NULL DEFAULT 'text',
	source_code TEXT NOT NULL,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT code_snippets_project_fk
		FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tags (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS todos (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	project_id BIGINT NOT NULL,
	title VARCHAR(255) NOT NULL,
	content TEXT NOT NULL DEFAULT '',
	completed BOOLEAN NOT NULL DEFAULT FALSE,
	completed_at TIMESTAMP,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT todos_project_fk
		FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS ideas (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	project_id BIGINT NOT NULL,
	title VARCHAR(255) NOT NULL,
	content TEXT NOT NULL DEFAULT '',
	converted BOOLEAN NOT NULL DEFAULT FALSE,
	converted_todo_id BIGINT,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	CONSTRAINT ideas_project_fk
		FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE,
	CONSTRAINT ideas_converted_todo_fk
		FOREIGN KEY (converted_todo_id) REFERENCES todos(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS idea_tags (
	idea_id BIGINT NOT NULL,
	tag_id BIGINT NOT NULL,
	CONSTRAINT idea_tags_idea_fk
		FOREIGN KEY (idea_id) REFERENCES ideas(id) ON DELETE CASCADE,
	CONSTRAINT idea_tags_tag_fk
		FOREIGN KEY (tag_id) REFERENCES tags(id) ON DELETE CASCADE,
	CONSTRAINT idea_tags_unique UNIQUE (idea_id, tag_id)
);

CREATE TABLE IF NOT EXISTS todo_tags (
	todo_id BIGINT NOT NULL,
	tag_id BIGINT NOT NULL,
	CONSTRAINT todo_tags_todo_fk
		FOREIGN KEY (todo_id) REFERENCES todos(id) ON DELETE CASCADE,
	CONSTRAINT todo_tags_tag_fk
		FOREIGN KEY (tag_id) REFERENCES tags(id) ON DELETE CASCADE,
	CONSTRAINT todo_tags_unique UNIQUE (todo_id, tag_id)
);

CREATE INDEX IF NOT EXISTS notes_project_id_idx ON notes(project_id);
CREATE INDEX IF NOT EXISTS code_snippets_project_id_idx ON code_snippets(project_id);
CREATE INDEX IF NOT EXISTS project_links_project_id_idx ON project_links(project_id);
CREATE INDEX IF NOT EXISTS todos_project_id_idx ON todos(project_id);
CREATE INDEX IF NOT EXISTS ideas_project_id_idx ON ideas(project_id);
CREATE INDEX IF NOT EXISTS idea_tags_tag_id_idx ON idea_tags(tag_id);
CREATE INDEX IF NOT EXISTS todo_tags_tag_id_idx ON todo_tags(tag_id);
